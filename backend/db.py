import os
import psycopg
from psycopg.rows import dict_row
from dotenv import load_dotenv

load_dotenv()


def get_conn():
    # One short-lived connection per request. Neon pools them for us.
    return psycopg.connect(os.environ["DATABASE_URL"], row_factory=dict_row)


SCHEMA = """
CREATE TABLE IF NOT EXISTS tickets (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) PRIMARY KEY,
    category        TEXT NOT NULL,
    location        TEXT,
    issue           TEXT NOT NULL,
    priority        TEXT NOT NULL CHECK (priority IN ('low','medium','high','critical')),
    priority_reason TEXT,
    time_constraint TEXT,
    status          TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open','resolved')),
    report_count    INTEGER NOT NULL DEFAULT 1,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
"""


def init_db():
    with get_conn() as conn:
        conn.execute(SCHEMA)


if __name__ == "__main__":
    init_db()
    with get_conn() as conn:
        n = conn.execute("SELECT count(*) AS n FROM tickets").fetchone()["n"]
    print(f"tickets table ready, {n} rows")